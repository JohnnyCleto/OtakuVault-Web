CREATE TABLE IF NOT EXISTS library_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id VARCHAR(24) NOT NULL,
 media_id INT NOT NULL,
 media_type ENUM('ANIME','MANGA') NOT NULL,
 status ENUM('PLANNING','CURRENT','COMPLETED','DROPPED','NOT_RECOMMENDED') NOT NULL DEFAULT 'PLANNING',
 progress INT NOT NULL DEFAULT 0,
 favorite BOOLEAN NOT NULL DEFAULT FALSE,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uniq_user_media (user_id,media_id)
);
CREATE TABLE IF NOT EXISTS history_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id VARCHAR(24) NOT NULL,
 media_id INT NOT NULL,
 viewed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_user_time (user_id,viewed_at)
);

CREATE TABLE IF NOT EXISTS user_media_snapshots (
 user_id VARCHAR(24) NOT NULL,
 media_id INT NOT NULL,
 title VARCHAR(300) NOT NULL,
 cover VARCHAR(1200) NOT NULL DEFAULT '',
 is_adult BOOLEAN NOT NULL DEFAULT FALSE,
 total INT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (user_id,media_id)
);
CREATE TABLE IF NOT EXISTS episode_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id VARCHAR(24) NOT NULL,
 media_id INT NOT NULL,
 episode INT NOT NULL,
 kind ENUM('ANIME','MANGA') NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_user_media_date (user_id, media_id, created_at)
);

